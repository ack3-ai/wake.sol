"""Base classes for the structured-error hierarchy (see ``_errors`` for the full
overview, ``build()`` resolution, and the ``must_revert`` / ``may_revert`` API).

This module holds only the hand-written category bases. The concrete leaf classes
(``AnchorError.ConstraintSeeds`` etc.) are real classes in the generated
``_errors_catalog`` package and are attached onto these bases at runtime by
``_errors`` (via ``setattr``). To keep the ``Base.LeafName`` spelling visible to
type checkers, each base re-declares its leaves under ``if TYPE_CHECKING:`` — the
blocks between the ``>>>GEN:<cat>>>>`` markers are generated by
``wake_sol._gen.errors_catalog`` and must not be hand-edited.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

