class ProgramError(TransactionFailed):
    """Base for program-defined errors (Custom codes, typically >= 6000).
    Each generated program gets a ``<Program>Error`` subclass of this."""


class UnknownError(TransactionFailed):
    """A ``Custom(code)`` that matched no registered program and no framework
    table — surfaced with its bare ``code`` rather than an invented name."""


